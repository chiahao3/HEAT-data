#!/usr/bin/env python3
"""Launch an archived search with paths resolved for this checkout."""
import argparse
import json
from pathlib import Path
import subprocess
import sys

ROOT = Path(__file__).resolve().parent


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("method", choices=["heat", "conventional"])
    parser.add_argument("case", choices=["h", "edge", "wse2"])
    parser.add_argument("--prepare-only", action="store_true",
                        help="Validate input paths and write YAML without starting a search.")
    parser.add_argument("--output-dir", type=Path,
                        help="New run directory; default: runs/METHOD/CASE in this checkout.")
    args = parser.parse_args()
    entry = json.loads((ROOT / "configs" / f"{args.method}_{args.case}.json").read_text())
    config = entry["config"]
    for section, key in entry["repository_paths"]:
        value = (ROOT / config[section][key]).resolve()
        if key != "output_dir" and not value.exists():
            parser.error(f"Missing input: {value}")
        config[section][key] = str(value)
    output = (args.output_dir or Path(config["paths"]["output_dir"])).resolve()
    config["paths"]["output_dir"] = str(output)
    output.mkdir(parents=True, exist_ok=True)
    path = output / "portable_config.yaml"
    lines = ["# Generated by run_search.py; no credentials are stored here."]
    for section, values in config.items():
        lines.append(section + ":")
        for key, value in values.items():
            lines.append(f"  {key}: {json.dumps(value)}")
    path.write_text("\n".join(lines) + "\n")
    command = [sys.executable, str(ROOT / entry["script"]), "--config", str(path)]
    print(f"Configuration: {path}", flush=True)
    if not args.prepare_only:
        subprocess.run(command, cwd=ROOT, check=True)


if __name__ == "__main__":
    main()
